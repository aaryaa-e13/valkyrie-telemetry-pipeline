"""SHA-256 lock for the jars that docker/spark/fetch_jars.sh adds to Spark.

Why: fetch_jars.sh resolves jars with Apache Ivy (spark-submit --packages), and
Ivy does not verify checksums there: in Phase 2 slice 1 it accepted an all-zero
.sha1, and over HTTP it never even requested the .sha1 file (docs/DECISIONS.md
D2.1). So integrity is pinned here instead: trust once (cross-checked against
Maven Central), then verify on every build.

Two commands (standard library only, runs inside the Spark image):

  verify    Every image build. Compares each added jar (the "add" lines in
            /opt/valkyrie/jars-*.txt) with the lock. Fails (exit 1) on
              MISMATCH  a jar's SHA-256 or coordinate differs from the lock,
              UNLISTED  a jar was added that the lock does not list,
              MISSING   the lock lists a jar that was not added / not present.
  generate  Only via `make jars-lock`, on purpose. Hashes the added jars,
            downloads Maven Central's published .sha1 for each over HTTPS,
            prints the comparison and fails if any differs or cannot be
            fetched. On success it writes the new lock to stdout, so an
            upgrade shows up as a reviewable git diff of jars.sha256.

Lock line format (sorted by file name, no timestamps, so diffs stay minimal):
    <sha256>  <jar file name>  <group:artifact:version>
"""

from __future__ import annotations

import argparse
import hashlib
import sys
import urllib.request
from collections.abc import Callable, Iterable
from dataclasses import dataclass
from pathlib import Path

CENTRAL = "https://repo1.maven.org/maven2"
LOCK_HEADER = (
    "# SHA-256 lock for jars added by docker/spark/fetch_jars.sh.\n"
    "# Generated by `make jars-lock` (each hash cross-checked against Maven Central's .sha1).\n"
    "# Verified on every image build by docker/spark/jars_lock.py. Do not edit by hand.\n"
)


@dataclass(frozen=True)
class LockEntry:
    """One locked jar."""

    sha256: str
    coord: str


def parse_lists(texts: Iterable[str]) -> dict[str, str]:
    """Collect {jar file: coordinate} from the "add" lines of fetch_jars.sh lists.

    Raises:
        ValueError: An add line has no coordinate, or a jar is added twice.
    """
    added: dict[str, str] = {}
    for text in texts:
        for raw in text.splitlines():
            parts = raw.split()
            if not parts or parts[0] != "add":
                continue
            if len(parts) != 3 or parts[2].count(":") != 2:
                raise ValueError(f"add line without group:artifact:version: {raw.strip()!r}")
            if parts[1] in added:
                raise ValueError(f"jar added twice: {parts[1]}")
            added[parts[1]] = parts[2]
    return added


def parse_lock(text: str) -> dict[str, LockEntry]:
    """Parse the lock file into {jar file: LockEntry}.

    Raises:
        ValueError: A line is malformed or a jar is listed twice.
    """
    lock: dict[str, LockEntry] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) != 3 or len(parts[0]) != 64:
            raise ValueError(f"malformed lock line: {raw!r}")
        if parts[1] in lock:
            raise ValueError(f"jar listed twice in lock: {parts[1]}")
        lock[parts[1]] = LockEntry(sha256=parts[0].lower(), coord=parts[2])
    return lock


def file_digest(path: Path, algo: str) -> str:
    """Hex digest of a file (streamed, so large jars do not fill memory)."""
    h = hashlib.new(algo)
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def verify(lock: dict[str, LockEntry], added: dict[str, str], jars_dir: Path) -> list[str]:
    """Return problems (empty list = every added jar matches the lock exactly)."""
    problems: list[str] = []
    for jar in sorted(added.keys() | lock.keys()):
        entry, coord = lock.get(jar), added.get(jar)
        path = jars_dir / jar
        if entry is None:
            problems.append(f"UNLISTED {jar} ({coord}) was added but is not in the lock")
            continue
        if coord is None:
            problems.append(f"MISSING  {jar} is in the lock but was not added")
            continue
        if not path.is_file():
            problems.append(f"MISSING  {jar} was added but is not in {jars_dir}")
            continue
        if coord != entry.coord:
            problems.append(f"MISMATCH {jar}: coordinate {coord}, lock says {entry.coord}")
        got = file_digest(path, "sha256")
        if got != entry.sha256:
            problems.append(f"MISMATCH {jar}: sha256 {got}, lock says {entry.sha256}")
    return problems


def central_sha1_url(coord: str) -> str:
    """Maven Central URL of the published .sha1 for a plain (no classifier) jar."""
    group, artifact, version = coord.split(":")
    return (f"{CENTRAL}/{group.replace('.', '/')}/{artifact}/{version}/"
            f"{artifact}-{version}.jar.sha1")


def fetch_central_sha1(url: str, timeout_s: float = 30.0) -> str:
    """Download a .sha1 file over HTTPS (certificate verified by default)."""
    if not url.startswith("https://"):
        raise ValueError(f"refusing non-HTTPS URL: {url}")
    with urllib.request.urlopen(url, timeout=timeout_s) as resp:
        body = resp.read(200).decode("ascii", "replace")
    token = body.split()[0].lower() if body.split() else ""
    if len(token) != 40:
        raise ValueError(f"unexpected .sha1 content at {url}: {body[:60]!r}")
    return token


def generate(added: dict[str, str], jars_dir: Path,
             fetch: Callable[[str], str] = fetch_central_sha1) -> tuple[str, list[str], bool]:
    """Build the lock text, a comparison report, and whether all cross-checks passed."""
    rows: list[str] = []
    lines: list[str] = []
    ok = True
    for jar in sorted(added):
        coord = added[jar]
        path = jars_dir / jar
        local_sha1 = file_digest(path, "sha1")
        url = central_sha1_url(coord)
        try:
            central = fetch(url)
        except Exception as exc:  # network, 404, malformed: all mean "not confirmed"
            central = f"ERROR {type(exc).__name__}: {exc}"
        same = central == local_sha1
        ok = ok and same
        rows.append(f"{'OK  ' if same else 'DIFF'} {jar}\n"
                    f"     local sha1   {local_sha1}\n     central sha1 {central}\n"
                    f"     {url}")
        lines.append(f"{file_digest(path, 'sha256')}  {jar}  {coord}")
    return LOCK_HEADER + "\n".join(lines) + "\n", rows, ok


def _added_from(list_paths: list[Path]) -> dict[str, str]:
    if not list_paths:
        raise SystemExit("no jar lists given")
    return parse_lists(p.read_text() for p in list_paths)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="SHA-256 lock for jars added by fetch_jars.sh")
    sub = p.add_subparsers(dest="cmd", required=True)
    v = sub.add_parser("verify", help="check added jars against the lock (every build)")
    v.add_argument("--lock", type=Path, required=True)
    v.add_argument("--jars-dir", type=Path, required=True)
    v.add_argument("--marker", type=Path, help="write this file when verification passes")
    v.add_argument("lists", type=Path, nargs="+")
    g = sub.add_parser("generate", help="write a new lock to stdout (make jars-lock)")
    g.add_argument("--jars-dir", type=Path, required=True)
    g.add_argument("lists", type=Path, nargs="+")
    args = p.parse_args(argv)

    added = _added_from(args.lists)
    if args.cmd == "verify":
        problems = verify(parse_lock(args.lock.read_text()), added, args.jars_dir)
        if problems:
            print(f"jar lock FAILED ({args.lock.name}):", file=sys.stderr)
            for problem in problems:
                print(f"  {problem}", file=sys.stderr)
            return 1
        msg = f"jar lock OK: {len(added)} added jars match {args.lock.name} (sha256)"
        if args.marker:
            args.marker.write_text(msg + "\n")
        print(msg)
        return 0

    text, rows, ok = generate(added, args.jars_dir)
    print("\n".join(rows), file=sys.stderr)
    if not ok:
        print("jars-lock FAILED: a local jar differs from Maven Central's .sha1 (or could not "
              "be checked). Lock NOT written.", file=sys.stderr)
        return 1
    print(f"jars-lock: {len(added)} jars cross-checked against Maven Central, all equal.",
          file=sys.stderr)
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
